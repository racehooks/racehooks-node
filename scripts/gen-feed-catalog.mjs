#!/usr/bin/env node
// Generates src/feed-catalog.generated.ts from catalog/feed-catalog.json
// (the vendored copy of the RaceHooks feed catalog, schema racehooks.feed-catalog/1).
// Usage: node scripts/gen-feed-catalog.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cat = JSON.parse(readFileSync(resolve(root, "catalog/feed-catalog.json"), "utf8"));

if (cat.schema !== "racehooks.feed-catalog/1") throw new Error(`unsupported catalog schema: ${cat.schema}`);
const hash = createHash("sha256").update(JSON.stringify({ families: cat.families, feeds: cat.feeds })).digest("hex");
if (hash !== cat.contentHash) {
  throw new Error(`catalog/feed-catalog.json is corrupt or hand-edited: contentHash ${cat.contentHash} != computed ${hash}`);
}

const q = (s) => JSON.stringify(s);
const union = (xs) => xs.map((x) => `  | ${q(x)}`).join("\n");
const tiers = [...new Set(cat.feeds.map((f) => f.tier))];
const families = cat.families.map((f) => f.category);

const rows = cat.feeds
  .map(
    (f) =>
      `  { id: ${q(f.feedId)}, name: ${q(f.name)}, family: ${q(f.family)}, tier: ${q(f.tier)}, description: ${q(f.shortDesc)}, cadence: ${q(f.cadence ?? null)} },`,
  )
  .join("\n");

const out = `// GENERATED by scripts/gen-feed-catalog.mjs from catalog/feed-catalog.json. Do not edit.

/** Feed availability tier, as published in the RaceHooks feed catalog. Not the account plan. */
export type FeedAvailability =
${union(tiers)};

/** Feed family (catalog category). */
export type FeedFamily =
${union(families)};

/**
 * The canonical set of RaceHooks feed ids (the \`feedId\` you pass to
 * \`webhooks.create\`, and the \`feed\` discriminator on delivered payloads).
 */
export type FeedId =
${union(cat.feeds.map((f) => f.feedId))};

export interface FeedCatalogEntry {
  id: FeedId;
  name: string;
  family: FeedFamily;
  tier: FeedAvailability;
  description: string;
  /** Delivery cadence, or null when the catalog does not state one. */
  cadence: string | null;
}

/** Content hash of the catalog this file was generated from. */
export const FEED_CATALOG_HASH = ${q(cat.contentHash)};

export const FEED_CATALOG: readonly FeedCatalogEntry[] = [
${rows}
];
`;
writeFileSync(resolve(root, "src/feed-catalog.generated.ts"), out);
console.log(`wrote src/feed-catalog.generated.ts (${cat.feeds.length} feeds, hash ${cat.contentHash.slice(0, 12)})`);
